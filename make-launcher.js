/**
 * WorkBuddy Typography Plugin - Launcher builder
 *
 * Creates a launcher that starts WorkBuddy with --remote-debugging-port,
 * which is required for the plugin to inject CSS via CDP.
 *
 * Design (v2):
 *   - The launcher .cmd lives in THIS plugin folder, not on the Desktop.
 *     Moving/deleting the Desktop item therefore never breaks the plugin.
 *   - We try to drop a .lnk on the Desktop pointing at that .cmd, purely
 *     as a convenience. If that fails (no PowerShell, policy, etc.) we
 *     simply print the manual steps -- nothing is broken.
 *
 * Why .cmd as the source of truth and not .lnk:
 *   - A .lnk is an MS-CFB binary container; hand-building one is fragile.
 *   - PowerShell COM may be unavailable or blocked.
 *   - A .cmd is plain text, inspectable, and works everywhere.
 *
 * Usage: node make-launcher.js [cdpPort] [workbuddyExe]
 */

const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync } = require('child_process');

const CDP_PORT = process.argv[2] || '9222';
const PLUGIN_DIR = __dirname;

// ---- locate WorkBuddy.exe -------------------------------------------------
// Installs vary a lot: D:\Programs, C:\Program Files, LOCALAPPDATA, per-user
// installs... so probe a list of candidates and let the user override with
//   setup-cdp.bat "C:\path\to\WorkBuddy.exe"
function findWorkBuddy() {
  if (process.argv[3]) return process.argv[3];
  const env = process.env;
  const roots = [
    'D:/Programs/WorkBuddy/WorkBuddy.exe',
    'C:/Program Files/WorkBuddy/WorkBuddy.exe',
    'C:/Program Files (x86)/WorkBuddy/WorkBuddy.exe',
    path.join(env.LOCALAPPDATA || '', 'Programs/WorkBuddy/WorkBuddy.exe'),
    path.join(env.LOCALAPPDATA || '', 'WorkBuddy/WorkBuddy.exe'),
  ];
  for (const p of roots) {
    try { if (p && fs.existsSync(p)) return p; } catch {}
  }
  return null; // caller reports
}

const WB_EXE = findWorkBuddy();

// Launcher lives with the plugin, NOT on the Desktop.
const cmdPath = path.join(PLUGIN_DIR, 'Start WorkBuddy.cmd');
const desktop = path.join(os.homedir(), 'Desktop');
const lnkPath = path.join(desktop, 'WorkBuddy (Typography).lnk');

function fail(msg, hint) {
  console.error('[typography] ERROR: ' + msg);
  if (hint) console.error('[typography] ' + hint);
  process.exit(1);
}

if (!WB_EXE) {
  fail('WorkBuddy.exe not found.',
       'Searched common install locations. Pass the path explicitly:\n' +
       '[typography]   setup-cdp.bat "C:\\path\\to\\WorkBuddy.exe"');
}

// ---- 1. the launcher .cmd (authoritative, lives in plugin dir) -----------
const cmd = [
  '@echo off',
  'REM ============================================================',
  'REM  WorkBuddy launcher WITH debug port, for the typography plugin.',
  'REM  Generated by WB-Typography. Safe to delete.',
  'REM  To start WorkBuddy normally, use your regular shortcut.',
  'REM ============================================================',
  'echo Starting WorkBuddy with CDP port ' + CDP_PORT + '...',
  'start "" "' + WB_EXE + '" --remote-debugging-port=' + CDP_PORT,
  'exit /b 0',
  '',
].join('\r\n');

try {
  fs.writeFileSync(cmdPath, cmd, 'ascii');
} catch (e) {
  fail('cannot write launcher: ' + e.message);
}
console.log('[typography] Launcher created -> ' + cmdPath);

// ---- 2. optional Desktop shortcut (convenience only) --------------------
function tryCreateShortcut() {
  if (!fs.existsSync(desktop)) {
    try { fs.mkdirSync(desktop, { recursive: true }); }
    catch { return false; }
  }
  // wscript.exe always exists on Windows; run the .cmd hidden.
  const helper = path.join(os.tmpdir(), 'wb-typo-lnk-' + process.pid + '.vbs');
  const vbs = [
    'Set s = CreateObject("WScript.Shell")',
    'Set l = s.CreateShortcut("' + lnkPath.replace(/"/g, '') + '")',
    'l.TargetPath = "cmd.exe"',
    'l.Arguments = "/c \\""' + cmdPath.replace(/"/g, '') + '\\""',
    'l.WorkingDirectory = "' + PLUGIN_DIR.replace(/"/g, '') + '"',
    'l.IconLocation = "' + WB_EXE.replace(/"/g, '') + ',0"',
    'l.Description = "WorkBuddy with typography plugin CDP port ' + CDP_PORT + '"',
    'l.Save()',
  ].join('\r\n');
  try {
    fs.writeFileSync(helper, vbs, 'ascii');
    execFileSync('wscript.exe', ['//nologo', helper], { stdio: 'pipe', timeout: 15000 });
    return true;
  } catch (e) {
    return false;
  } finally {
    try { fs.unlinkSync(helper); } catch {}
  }
}

let lnkOk = false;
try { lnkOk = tryCreateShortcut(); } catch {}

console.log('');
if (lnkOk) {
  console.log('[typography] Desktop shortcut -> ' + lnkPath);
  console.log('');
  console.log('[typography] NEXT STEPS:');
  console.log('  1. Close WorkBuddy completely (all windows + tray icon)');
  console.log('  2. Start WorkBuddy from the Desktop shortcut');
  console.log('  3. Run settings.bat to open the font settings page');
} else {
  console.log('[typography] Could not auto-create a Desktop shortcut.');
  console.log('[typography] That is not a problem - the launcher works where it is:');
  console.log('');
  console.log('   >>> ' + cmdPath + ' <<<');
  console.log('');
  console.log('[typography] To make it easy to click, do either:');
  console.log('  A) Right-click the file above -> "Send to" -> "Desktop (create shortcut)"');
  console.log('  B) Or just double-click it whenever you want to start WorkBuddy');
  console.log('');
  console.log('[typography] NEXT STEPS:');
  console.log('  1. Close WorkBuddy completely (all windows + tray icon)');
  console.log('  2. Start WorkBuddy using the launcher above');
  console.log('  3. Run settings.bat to open the font settings page');
}
console.log('');
console.log('[typography] The launcher is per-Windows-account, not machine-wide.');
console.log('[typography] The plugin itself IS machine-wide: ' + PLUGIN_DIR);
